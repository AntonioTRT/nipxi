EXPORT_VERSION = "1.0"
DEFAULT_GZIP_THRESHOLD_BYTES = 10 * 1024 * 1024  # 10 MB -- see write_export()'s docstring

DESCRIPTION = (
    "This is a self-contained forensic export of one battery-test run, generated by "
    "scripts/export_run.py for AI-assisted incident investigation. Read 'incident_summary' "
    "first for an instant digest of what happened; 'timeline' gives full merged chronology "
    "(event_log + execution_state, already sorted -- no need to reconstruct it from separate "
    "tables); 'safety' and 'forensic_findings' give correlated safety-fault detail (raised/"
    "acknowledged pairs already joined by fault_id); 'critical_events' is a filtered view of "
    "'timeline' containing only safety/error-severity entries. 'run_summary', "
    "'execution_state', 'event_log', 'measurements', and 'raw_hardware_log' are the "
    "underlying raw records everything above is derived from. Every field in "
    "'incident_summary'/'safety'/'forensic_findings' is a deterministic lookup from stored "
    "data, computed by Python code -- none of it is AI-generated, inferred, or scored."
)

ROOT_CAUSE_CAVEAT = (
    "verification_result describes the failure mode observed (what the SMU readback "
    "reported), not a diagnosis of the underlying physical cause -- STILL_ENABLED means the "
    "output was electrically confirmed on, not why the disable command failed to take "
    "effect (a driver fault, a stuck relay, and a firmware hang would all look identical "
    "from this field alone)."
)

# Timeline severity for a station_state transition -- event_log rows
# already carry a real `level` column; station_state does not, so this is
# the one small curated mapping needed to give station_state entries a
# comparable severity for the critical_events filter.
_STATE_SEVERITY = {
    "STATION_FAULT": "CRITICAL",
    "SAFETY_VIOLATION": "CRITICAL",
    "FAILED": "ERROR",
    "CANCELLED": "WARNING",
}

# Always promoted into critical_events regardless of event_log.level --
# see docs/architecture.md "Forensic Export"/"Critical Events": some of
# these (SAFETY_FAULT_ACKNOWLEDGED) are correctly logged at level=INFO
# (an acknowledgement is a resolution, not a problem) but are still one of
# the golden forensic questions ("did the operator acknowledge?") and must
# never be filtered out by a bare level check.
ALWAYS_CRITICAL_EVENT_TYPES = frozenset({
    EventType.SAFETY_FAULT_RAISED,
    EventType.SAFETY_FAULT_ACKNOWLEDGED,
    EventType.GROUP_RUN_ABORTED_STATION_FAULT,
    EventType.SAFETY_MONITOR_TRIGGERED,
})


class ExportError(Exception):
    """Raised when run_id itself cannot be found -- nothing to export."""


# -----------------------------------------------------------------------
# Section builders -- each is a pure function over already-fetched rows,
# so they're independently unit-testable without a database.
# -----------------------------------------------------------------------

def _build_timeline(event_rows: list, station_state_rows: list) -> list:
    """
    Merge event_log + station_state into one chronologically-sorted list
    -- see docs/architecture.md "Timeline". Deliberately excludes
    raw_hardware_log (too high-volume, and safety-relevant rows there are
    already represented via event_log's SAFETY_FAULT_RAISED entries).
    """
    entries = []
    for row in event_rows:
        parsed = parse_event_fields(row["message"])
        entries.append({
            "timestamp": row["timestamp"],
            "source": "event_log",
            "event": parsed.get("event_type", "LOG_MESSAGE"),
            "detail": row["message"],
            "severity": row.get("level") or "INFO",
        })
    for row in station_state_rows:
        state = row.get("state")
        detail_bits = [f"{k}={row[k]}" for k in ("channel", "relay") if row.get(k) is not None]
        detail = f"state={state}" + (" " + " ".join(detail_bits) if detail_bits else "")
        entries.append({
            "timestamp": row["timestamp"],
            "source": "station_state",
            "event": state,
            "detail": detail,
            "severity": _STATE_SEVERITY.get(state, "INFO"),
        })
    entries.sort(key=lambda e: e["timestamp"])
    return entries


def _build_critical_events(timeline: list) -> list:
    """
    A filtered VIEW of `timeline`, not an independently-populated list --
    see docs/architecture.md "Critical Events": two lists maintained
    separately is exactly the kind of thing that silently drifts apart.
    """
    return [
        entry for entry in timeline
        if entry["severity"] in ("ERROR", "CRITICAL") or entry["event"] in ALWAYS_CRITICAL_EVENT_TYPES
    ]


def _build_safety_section(event_rows: list) -> dict:
    """
    Dedicated safety section -- joins SAFETY_FAULT_RAISED with its
    SAFETY_FAULT_ACKNOWLEDGED via fault_id, so the AI never has to do
    this correlation itself (see docs/architecture.md "Safety Section").
    """
    raised, acknowledged_at_by_fault_id = [], {}
    for row in event_rows:
        fields = parse_safety_fault_event(row["message"])
        if not fields:
            continue
        if fields["event_type"] == EventType.SAFETY_FAULT_RAISED:
            raised.append({"_row_timestamp": row["timestamp"], **fields})
        elif fields["event_type"] == EventType.SAFETY_FAULT_ACKNOWLEDGED:
            acknowledged_at_by_fault_id[fields.get("acknowledges_fault_id")] = row["timestamp"]

    fault_timeline = []
    for fault in raised:
        fault_id = fault.get("fault_id")
        verification_result = fault.get("verification_result")
        fault_timeline.append({
            "fault_id": fault_id,
            "raised_at": fault["_row_timestamp"],
            "acknowledged_at": acknowledged_at_by_fault_id.get(fault_id),
            "device_name": fault.get("device_name"),
            "device_type": fault.get("device_type"),
            "position": fault.get("position"),
            "context": fault.get("context"),
            "source_method": fault.get("source_method"),
            "reason": fault.get("reason"),
            "verification_result": verification_result,
            "verification_result_meaning": (
                verification_result_meaning(verification_result) if verification_result else None
            ),
        })

    return {
        "available": True,
        "reason": None,
        "fault_count": len(fault_timeline),
        "acknowledged_count": sum(1 for f in fault_timeline if f["acknowledged_at"] is not None),
        "fault_timeline": fault_timeline,
    }


def _unavailable_safety_section(reason: str) -> dict:
    """
    Telemetry unavailable -- see module docstring: fault counts must be
    None (unknown), never 0 (which would falsely read as "confirmed
    clean"). event_log (the safety section's only source) lives in the
    telemetry database, so an unreachable telemetry file means the safety
    section genuinely cannot be assessed, not that nothing happened.
    """
    return {"available": False, "reason": reason, "fault_count": None,
            "acknowledged_count": None, "fault_timeline": []}


def _build_forensic_findings(fault_timeline: list) -> list:
    """
    Deterministic interpretation layer -- see docs/architecture.md
    "Forensic Findings". NO heuristics, NO confidence scoring: every
    value is a fixed lookup (FORENSIC_FINDINGS_BY_VERIFICATION_RESULT)
    keyed only by the stored verification_result string. Cross-referenced
    to the `safety` section by fault_id -- device/position/reason/etc.
    live there, not duplicated here.
    """
    findings = []
    for fault in fault_timeline:
        verification_result = fault.get("verification_result")
        mapping = FORENSIC_FINDINGS_BY_VERIFICATION_RESULT.get(
            verification_result, {"physical_state_confidence": "UNKNOWN", "communication_failure": None},
        )
        findings.append({
            "fault_id": fault["fault_id"],
            "verification_result": verification_result,
            "physical_state_confidence": mapping["physical_state_confidence"],
            "communication_failure": mapping["communication_failure"],
            "operator_acknowledged": fault["acknowledged_at"] is not None,
        })
    return findings


def _testing_continued_after_fault(event_rows: list, primary_fault: dict) -> bool:
    """
    Scoped to THIS run_id only -- see docs/architecture.md "Incident
    Summary": whether a DIFFERENT position in the same Group -> ALL run
    continued afterward is a cross-run question outside what a single
    run's export can answer. Within one run, a fault is normally terminal
    (the raising sequence re-raises immediately after acknowledgement),
    so False is the expected, correct answer in the common case -- this
    field exists to positively CONFIRM that, not to detect an anomaly.
    """
    if primary_fault is None:
        return False
    reference_time = primary_fault.get("acknowledged_at") or primary_fault.get("raised_at")
    if reference_time is None:
        return False
    return any(row["timestamp"] > reference_time for row in event_rows)


def _build_narrative(run: dict, primary_fault, operator_acknowledged, testing_continued,
                      telemetry_available: bool) -> str:
    """Template-filled, deterministic -- see module docstring. Never an
    LLM call; that would reintroduce non-determinism into a forensic
    artifact whose entire value is being reproducible and auditable."""
    if not telemetry_available:
        return (
            f"Run {run.get('run_id')} ({run.get('test_type')}): result={run.get('result')}, "
            f"stop_reason={run.get('stop_reason')}. Safety fault detail unavailable -- "
            f"telemetry database not accessible for this run."
        )
    if primary_fault is None:
        return (
            f"Run {run.get('run_id')} ({run.get('test_type')}) completed with "
            f"result={run.get('result')}, stop_reason={run.get('stop_reason')}."
        )
    verification_result = primary_fault.get("verification_result")
    label = verification_result.upper() if verification_result else "UNKNOWN"
    ack_clause = "Operator acknowledged." if operator_acknowledged else "NOT acknowledged."
    continued_clause = "Testing continued afterward." if testing_continued else "Testing did not continue."
    return f"SAFETY FAULT: Output could not be verified OFF ({label}). {ack_clause} {continued_clause}"


def _build_incident_summary(run: dict, station_state_rows: list, safety_section: dict,
                             event_rows: list, telemetry_available: bool) -> dict:
    """The 30-second digest -- see docs/architecture.md "Incident
    Summary". Every field is a deterministic lookup/derivation from
    already-computed data; nothing here re-queries or re-interprets."""
    final_execution_state = station_state_rows[-1]["state"] if station_state_rows else None

    if not safety_section["available"]:
        fault_count = acknowledged_count = operator_acknowledged = testing_continued = None
        primary = None
    else:
        fault_timeline = safety_section["fault_timeline"]
        fault_count = safety_section["fault_count"]
        acknowledged_count = safety_section["acknowledged_count"]
        operator_acknowledged = acknowledged_count > 0
        primary = fault_timeline[0] if fault_timeline else None
        testing_continued = _testing_continued_after_fault(event_rows, primary) if primary else False

    additional_fault_count = max(0, fault_count - 1) if fault_count is not None else None

    return {
        "run_id": run.get("run_id"),
        "station_id": run.get("station_id"),
        "station_name": run.get("station_name"),
        "result": run.get("result"),
        "stop_reason": run.get("stop_reason"),
        "duration_s": run.get("duration_s"),
        "final_execution_state": final_execution_state,
        "safety_fault_count": fault_count,
        "acknowledged_fault_count": acknowledged_count,
        "operator_acknowledged": operator_acknowledged,
        "testing_continued_after_fault": testing_continued,
        "primary_failure_mode": primary.get("verification_result") if primary else None,
        "primary_device": primary.get("device_name") if primary else None,
        "additional_fault_count": additional_fault_count,
        "root_cause_caveat": ROOT_CAUSE_CAVEAT if primary else None,
        "narrative": _build_narrative(run, primary, operator_acknowledged, testing_continued, telemetry_available),
    }


def _build_event_log_section(event_rows: list) -> list:
    """Every event_log row, plus a `parsed_fields` dict for any row in
    the EVENT_TYPE=... format -- saves the AI from re-parsing KEY=value
    text it has already been handed once, structured, in `safety`."""
    entries = []
    for row in event_rows:
        entry = dict(row)
        parsed = parse_event_fields(row["message"])
        if parsed:
            entry["parsed_fields"] = parsed
        entries.append(entry)
    return entries


def _channel_stats(rows: list, field: str) -> dict:
    values = [row[field] for row in rows if row.get(field) is not None]
    if not values:
        return {}
    return {f"min_{field}": min(values), f"max_{field}": max(values), f"avg_{field}": sum(values) / len(values)}


def _build_measurements_section(rows: list, include_full: bool, telemetry_available: bool, reason: str,
                                 sample_size: int = 10) -> dict:
    """
    Default: row_count + per-channel stats + first/last sample + a
    bounded sample -- ALWAYS present regardless of `include_full`, since
    these are cheap aggregates, not a row dump (see docs/architecture.md
    "Measurements" -- "always include, even when full rows are omitted").
    Full rows only with --include-measurements.
    """
    if not telemetry_available:
        return {"available": False, "reason": reason, "row_count": None}

    row_count = len(rows)
    per_channel: dict = {}
    for row in rows:
        channel_key = str(row.get("channel"))
        per_channel.setdefault(channel_key, []).append(row)
    per_channel_statistics = {
        channel_key: {
            **_channel_stats(channel_rows, "voltage_v"),
            **_channel_stats(channel_rows, "current_a"),
            **_channel_stats(channel_rows, "temp_c"),
        }
        for channel_key, channel_rows in per_channel.items()
    }

    if row_count <= sample_size * 2:
        sample = rows
    else:
        sample = rows[:sample_size] + rows[-sample_size:]

    return {
        "available": True,
        "row_count": row_count,
        "per_channel_statistics": per_channel_statistics,
        "first_sample": rows[0] if rows else None,
        "last_sample": rows[-1] if rows else None,
        "sample": None if include_full else sample,
        "full_rows_included": include_full,
        "rows": rows if include_full else None,
    }


def _decode_json_field(value):
    if not value:
        return value
    try:
        return json.loads(value)
    except (json.JSONDecodeError, TypeError):
        return value  # e.g. a repr() fallback from data/raw_hardware_log.py::_safe_json()


def _build_raw_hardware_log_section(rows: list, include_full: bool, telemetry_available: bool, reason: str) -> dict:
    """
    Default: count + distinct error_types only -- see docs/architecture.md
    "Raw Hardware Log" ("always include, even when not embedded"). Full
    rows (with command_parameters/response/additional_metadata decoded
    from JSON text into nested objects, not left as double-encoded
    strings) only with --include-raw-hardware-log.
    """
    if not telemetry_available:
        return {"available": False, "reason": reason, "hardware_failure_count": None, "unique_error_types": []}

    failures = [row for row in rows if not row.get("success")]
    unique_error_types = sorted({row["error_type"] for row in failures if row.get("error_type")})

    section = {
        "available": True,
        "row_count": len(rows),
        "hardware_failure_count": len(failures),
        "unique_error_types": unique_error_types,
        "full_rows_included": include_full,
        "rows": None,
    }
    if include_full:
        decoded_rows = []
        for row in rows:
            decoded = dict(row)
            for field in ("command_parameters", "response", "additional_metadata"):
                decoded[field] = _decode_json_field(decoded.get(field))
            decoded_rows.append(decoded)
        section["rows"] = decoded_rows
    return section


def _run_ref(row: dict) -> dict:
    return {
        "run_id": row.get("run_id"), "test_type": row.get("test_type"),
        "stop_reason": row.get("stop_reason"), "result": row.get("result"),
    }


def _build_related_runs(*, parent_run: dict, child_runs: list) -> dict:
    """
    Cycle/phase forensic linkage (see data/storage.py's `parent_run_id`
    column and test_control/cycle_sequence.py) -- lets a reader/AI walk
    from a CycleSequence phase row to its umbrella cycle_battery row, or
    from a cycle_battery row to its charge/discharge phase rows, WITHOUT a
    second export_run.py invocation or a fragile group_name/position/time-
    proximity heuristic. Both lists are empty/null for a run that has no
    cycle relationship at all (every non-CycleSequence run_id).
    """
    return {
        "parent": _run_ref(parent_run) if parent_run else None,
        "children": [_run_ref(row) for row in child_runs],
    }


def _build_metadata(*, run_id: str, run: dict, telemetry_available: bool,
                     telemetry_unavailable_reason, flags: dict, sections_included: list) -> dict:
    return {
        "export_version": EXPORT_VERSION,
        "exported_at": datetime.now().isoformat(),
        "run_id": run_id,
        "telemetry_db": run.get("telemetry_db"),
        "telemetry_available": telemetry_available,
        "telemetry_unavailable_reason": telemetry_unavailable_reason,
        "generator": "scripts/export_run.py",
        "flags": flags,
        "sections_included": sections_included,
        "description": DESCRIPTION,
    }


