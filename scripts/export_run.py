"""
Forensic export -- produce a single, self-contained JSON (or JSON.gz)
artifact for ONE run_id, suitable for uploading directly to an AI system
(Claude, Copilot, or a future forensic tool) for incident investigation --
see docs/architecture.md "Forensic Export".

Usage:
    python scripts/export_run.py RACK01-00000001
    python scripts/export_run.py RACK01-00000001 --summary-only
    python scripts/export_run.py RACK01-00000001 --include-measurements --include-raw-hardware-log
    python scripts/export_run.py RACK01-00000001 --gzip
    python scripts/export_run.py RACK01-00000001 --output /path/to/file.json

Design principles (see docs/architecture.md for the full review this
implements):

  - Read-only, zero side effects: uses DataStorage.open_for_forensic_
    export() -- never allocates a run_sequence value, never creates
    schema, never creates a CSV directory, never mutates either database.
  - Locates telemetry ONLY via the stored run_summary.telemetry_db column
    -- never inferred from a timestamp, never guessed.
  - `incident_summary`/`safety`/`forensic_findings` are 100% deterministic
    rollups of stored data -- nothing here is AI-generated or a heuristic
    guess. `narrative` is a template-filled sentence, not free text.
  - Telemetry-unavailable is never silently treated as "no faults" -- see
    _unavailable_safety_section() below: fault counts become None
    (unknown), never 0 (confirmed clean), whenever the source data
    (event_log, which lives in the telemetry database) could not be read.
"""

