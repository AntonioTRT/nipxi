def build_export(run_id: str, *, settings=Settings, summary_only: bool = False,
                  include_measurements: bool = False, include_raw_hardware_log: bool = False) -> dict:
    """
    Assemble the complete forensic export dict for `run_id`. Raises
    ExportError only if run_id itself cannot be found in the index
    database -- a run that IS found but has unreachable telemetry is NOT
    an error: every index-database-backed section is still exported in
    full, and every telemetry-dependent section is marked unavailable
    with an explicit reason (see module docstring).
    """
    storage, error = DataStorage.open_for_forensic_export(settings, run_id)
    if storage is None:
        raise ExportError(error)

    try:
        run = storage.get_run_summary(run_id)
        telemetry_available = storage._db is not None
        unavailable_reason = storage.telemetry_unavailable_reason
        station_state_rows = storage.get_station_state_for_run(run_id)
        child_runs = storage.get_child_run_summaries(run_id)
        parent_run = storage.get_run_summary(run["parent_run_id"]) if run and run.get("parent_run_id") else None
        if telemetry_available:
            event_rows = storage.get_recent_events(run_id=run_id, limit=None)
            measurement_rows = storage.get_measurements(run_id=run_id)
            raw_rows = storage.get_raw_hardware_log(run_id)
        else:
            event_rows, measurement_rows, raw_rows = [], [], []
    finally:
        storage.close()

    safety_section = (
        _build_safety_section(event_rows) if telemetry_available
        else _unavailable_safety_section(unavailable_reason)
    )
    forensic_findings = _build_forensic_findings(safety_section["fault_timeline"])
    incident_summary = _build_incident_summary(
        run, station_state_rows, safety_section, event_rows, telemetry_available,
    )
    related_runs = _build_related_runs(parent_run=parent_run, child_runs=child_runs)

    if summary_only:
        timeline, critical_events, execution_state, event_log = [], [], [], []
    else:
        timeline = _build_timeline(event_rows, station_state_rows)
        critical_events = _build_critical_events(timeline)
        execution_state = station_state_rows
        event_log = _build_event_log_section(event_rows)

    measurements = _build_measurements_section(measurement_rows, include_measurements, telemetry_available, unavailable_reason)
    raw_hardware_log = _build_raw_hardware_log_section(raw_rows, include_raw_hardware_log, telemetry_available, unavailable_reason)

    sections_included = ["metadata", "incident_summary", "safety", "forensic_findings", "run_summary", "related_runs"]
    if not summary_only:
        sections_included += ["timeline", "critical_events", "execution_state", "event_log"]
    if include_measurements:
        sections_included.append("measurements")
    if include_raw_hardware_log:
        sections_included.append("raw_hardware_log")

    metadata = _build_metadata(
        run_id=run_id, run=run, telemetry_available=telemetry_available,
        telemetry_unavailable_reason=unavailable_reason,
        flags={
            "summary_only": summary_only, "include_measurements": include_measurements,
            "include_raw_hardware_log": include_raw_hardware_log,
        },
        sections_included=sections_included,
    )

    # Key order matches the approved top-level order exactly -- json.dump()
    # preserves dict insertion order; NEVER pass sort_keys=True downstream,
    # that would alphabetize and destroy this deliberate ordering.
    # `related_runs` is a later, additive field (cycle/phase linkage via
    # parent_run_id) -- placed immediately after `run_summary` since it's
    # directly about that section, not part of the original approved order.
    return {
        "metadata": metadata,
        "incident_summary": incident_summary,
        "timeline": timeline,
        "safety": safety_section,
        "forensic_findings": forensic_findings,
        "critical_events": critical_events,
        "run_summary": run,
        "related_runs": related_runs,
        "execution_state": execution_state,
        "event_log": event_log,
        "measurements": measurements,
        "raw_hardware_log": raw_hardware_log,
    }


def _resolve_output_path(output_path, run_id: str, use_gzip: bool) -> str:
    if output_path is None:
        base = f"{run_id}.json"
    else:
        base = output_path[:-3] if output_path.endswith(".gz") else output_path
        if not base.endswith(".json"):
            base = f"{base}.json"
    return f"{base}.gz" if use_gzip else base


def write_export(export: dict, *, run_id: str, output_path: str = None, gzip_flag: bool = None,
                  size_threshold_bytes: int = DEFAULT_GZIP_THRESHOLD_BYTES) -> str:
    """
    Serialize `export` to pretty-printed JSON and write it to disk.

    `gzip_flag=True`/`False` forces the choice regardless of size;
    `gzip_flag=None` (default) auto-switches to `.json.gz` only if the
    serialized payload exceeds `size_threshold_bytes` -- most AI upload
    surfaces accept plain JSON directly but won't necessarily decompress
    `.gz` automatically, so gzip is never the silent default. Returns the
    actual path written.
    """
    payload = json.dumps(export, indent=2, sort_keys=False, default=str)
    payload_bytes = payload.encode("utf-8")
    use_gzip = gzip_flag if gzip_flag is not None else len(payload_bytes) > size_threshold_bytes

    path = _resolve_output_path(output_path, run_id, use_gzip)
    if use_gzip:
        with gzip.open(path, "wt", encoding="utf-8") as f:
            f.write(payload)
    else:
        with open(path, "w", encoding="utf-8") as f:
            f.write(payload)
    return path


